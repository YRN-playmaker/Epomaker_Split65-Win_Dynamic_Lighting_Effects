#!/usr/bin/env python3
"""Expand the TinyUSB Lighting macro used by Microsoft's RP2040 sample.
The checked-in upstream macro is the reference, not a hand-retyped descriptor.
Use --check to verify the generated bytes without writing.
"""
from pathlib import Path
import subprocess, tempfile, sys
root = Path(__file__).resolve().parents[1]
# USB HID Usage Tables Lighting and Illumination page.
usages = {
 'LAMP_ARRAY':1,'LAMP_ARRAY_ATTRIBUTES_REPORT':2,'LAMP_COUNT':3,
 'BOUNDING_BOX_WIDTH_IN_MICROMETERS':4,'BOUNDING_BOX_HEIGHT_IN_MICROMETERS':5,
 'BOUNDING_BOX_DEPTH_IN_MICROMETERS':6,'LAMP_ARRAY_KIND':7,'MIN_UPDATE_INTERVAL_IN_MICROSECONDS':8,
 'LAMP_ATTRIBUTES_REQUEST_REPORT':0x20,'LAMP_ID':0x21,'LAMP_ATTRIBUTES_RESPONSE_REPORT':0x22,
 'POSITION_X_IN_MICROMETERS':0x23,'POSITION_Y_IN_MICROMETERS':0x24,'POSITION_Z_IN_MICROMETERS':0x25,
 'LAMP_PURPOSES':0x26,'UPDATE_LATENCY_IN_MICROSECONDS':0x27,'RED_LEVEL_COUNT':0x28,
 'GREEN_LEVEL_COUNT':0x29,'BLUE_LEVEL_COUNT':0x2A,'INTENSITY_LEVEL_COUNT':0x2B,
 'IS_PROGRAMMABLE':0x2C,'INPUT_BINDING':0x2D,'LAMP_MULTI_UPDATE_REPORT':0x50,
 'RED_UPDATE_CHANNEL':0x51,'GREEN_UPDATE_CHANNEL':0x52,'BLUE_UPDATE_CHANNEL':0x53,
 'INTENSITY_UPDATE_CHANNEL':0x54,'LAMP_UPDATE_FLAGS':0x55,'LAMP_RANGE_UPDATE_REPORT':0x60,
 'LAMP_ID_START':0x61,'LAMP_ID_END':0x62,'LAMP_ARRAY_CONTROL_REPORT':0x70,'AUTONOMOUS_MODE':0x71,
}
encoding = r'''
#include <stdint.h>
#include <stdio.h>
#define HID_USAGE_PAGE_LIGHTING_AND_ILLUMINATION 0x59
#define HID_USAGE_PAGE(x) 0x05,(x)
#define HID_USAGE(x) 0x09,(x)
#define HID_COLLECTION_APPLICATION 1
#define HID_COLLECTION_LOGICAL 2
#define HID_COLLECTION(x) 0xA1,(x)
#define HID_COLLECTION_END 0xC0
#define HID_REPORT_ID(x) 0x85,(x),
#define HID_LOGICAL_MIN(x) 0x15,(x)
#define HID_LOGICAL_MAX(x) 0x25,(x)
#define HID_LOGICAL_MAX_N(x,n) HID_LOGICAL_MAX_N_##n(x)
#define HID_LOGICAL_MAX_N_2(x) 0x26,((x)&255),(((x)>>8)&255)
#define HID_LOGICAL_MAX_N_3(x) 0x27,((x)&255),(((x)>>8)&255),(((x)>>16)&255),(((x)>>24)&255)
#define HID_REPORT_SIZE(x) 0x75,(x)
#define HID_REPORT_COUNT(x) 0x95,(x)
#define HID_FEATURE(x) 0xB1,(x)
#define HID_CONSTANT 1
#define HID_DATA 0
#define HID_VARIABLE 2
#define HID_ABSOLUTE 0
'''
for name, value in usages.items(): encoding += f'#define HID_USAGE_LIGHTING_{name} {value}\n'
encoding += '#include "tinyusb-lighting-macro.h"\n'
encoding += 'static const uint8_t bytes[]={TUD_HID_REPORT_DESC_LIGHTING(0x20)};\nint main(void){return fwrite(bytes,1,sizeof(bytes),stdout)!=sizeof(bytes);}\n'
with tempfile.TemporaryDirectory() as temp:
 p=Path(temp); (p/'expand.c').write_text(encoding)
 subprocess.run(['gcc','-std=c11','-Wall','-Wextra','-Werror','-I',str(root/'tests/fixtures'),str(p/'expand.c'),'-o',str(p/'expand')],check=True)
 data=subprocess.check_output([str(p/'expand')])
header='// Copyright (c) 2019 Ha Thach (tinyusb.org)\n// SPDX-License-Identifier: MIT\n// Generated from TinyUSB TUD_HID_REPORT_DESC_LIGHTING, used by Microsoft RP2040 sample.\n// Report IDs 0x20..0x25 avoid QMK keyboard/mouse/media IDs on shared interface 0.\n'
text=header+''.join('    '+', '.join(f'0x{x:02X}' for x in data[i:i+12])+',\n' for i in range(0,len(data),12))
path=root/'dynamic_lighting/descriptor.inc'
if '--check' in sys.argv:
 assert path.read_text()==text, 'Descriptor differs from the reference TinyUSB macro'
 print(f'PASS: {len(data)} descriptor bytes match the upstream macro used by the Microsoft sample')
else:
 path.write_text(text); print(f'Generated {len(data)} descriptor bytes')
